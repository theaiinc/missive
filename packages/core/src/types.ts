// ──────────────────────────────────────────────
// Rule — AI-generated organization rules with user approval
// ──────────────────────────────────────────────

/** Conditions that can be checked against a missive */
export const RuleConditionSchema = z.object({
  field: z.enum([
    "from_address",       // sender email matches
    "from_domain",        // sender domain matches
    "subject_contains",   // subject includes text
    "subject_matches",    // subject regex
    "body_contains",      // body includes text
    "has_attachments",    // boolean
    "channel",            // email, chat, etc.
    "classification",     // invoice, lead, etc.
    "account_email",      // which account received it
    "received_after",     // time-based
    "received_before",
    "direction",          // inbound / outbound
  ]),
  operator: z.enum(["equals", "not_equals", "contains", "not_contains", "matches", "before", "after"]),
  value: z.string(),
});
export type RuleCondition = z.infer<typeof RuleConditionSchema>;

/** Actions to take when a rule matches */
export const RuleActionSchema = z.object({
  type: z.enum([
    "move_to_folder",     // move to a folder
    "mark_read",          // mark as read
    "mark_unread",        // mark as unread
    "archive",            // archive (move to archived folder)
    "label",              // add a classification label
    "delete",             // send to trash
    "forward",            // forward to email (future)
    "notify",             // send a notification
  ]),
  // Extra params depend on type:
  // move_to_folder → params: { folder: "invoices" }
  // label → params: { label: "important" }
  params: z.record(z.string()).optional(),
});
export type RuleAction = z.infer<typeof RuleActionSchema>;

export const RuleSchema = z.object({
  id: z.string(),
  name: z.string(),
  description: z.string().optional(),      // human-readable explanation
  enabled: z.boolean(),
  conditions: z.array(RuleConditionSchema),
  // AND logic: all conditions must match for the rule to fire
  actions: z.array(RuleActionSchema),
  // All actions run in sequence
  priority: z.number().optional(),         // higher = evaluated first
  appliedCount: z.number().optional(),     // how many times it matched
  lastAppliedAt: z.string().datetime().optional(),
  createdAt: z.string().datetime(),
  updatedAt: z.string().datetime(),
});
export type Rule = z.infer<typeof RuleSchema>;

/** A rule proposal returned by the AI before user approval */
export const RuleProposalSchema = z.object({
  name: z.string(),
  description: z.string(),
  conditions: z.array(RuleConditionSchema),
  actions: z.array(RuleActionSchema),
  clarification: z.string().optional(),    // if the AI needs to ask something
  needsClarification: z.boolean(),         // true = need more info from user
});
export type RuleProposal = z.infer<typeof RuleProposalSchema>;

// ──────────────────────────────────────────────
