import { z } from "zod";

// ──────────────────────────────────────────────
// Missive — A communication artifact
// ──────────────────────────────────────────────

export const MissiveChannel = z.enum([
  "email",
  "chat",
  "ticket",
  "comment",
  "sms",
  "notification",
  "social",
]);
export type MissiveChannel = z.infer<typeof MissiveChannel>;

export const MissiveDirection = z.enum(["inbound", "outbound"]);
export type MissiveDirection = z.infer<typeof MissiveDirection>;

export const ConnectorProvider = z.enum([
  "gmail",
  "outlook",
  "slack",
  "discord",
  "facebook",
  "whatsapp",
  "crm",
  "helpdesk",
  "imap",
]);
export type ConnectorProvider = z.infer<typeof ConnectorProvider>;

export const MissiveStatus = z.enum([
  "unread",
  "read",
  "archived",
  "deleted",
]);
export type MissiveStatus = z.infer<typeof MissiveStatus>;

export const MissiveSchema = z.object({
  id: z.string().ulid(),
  threadId: z.string().ulid(),
  channel: MissiveChannel,
  direction: MissiveDirection,
  provider: ConnectorProvider,
  providerMessageId: z.string(),
  subject: z.string().optional(),
  body: z.string(),
  bodyHtml: z.string().optional(),
  summary: z.string().optional(),
  from: z.object({
    name: z.string().optional(),
    address: z.string(),
  }),
  to: z.array(
    z.object({
      name: z.string().optional(),
      address: z.string(),
    })
  ),
  cc: z
    .array(
      z.object({
        name: z.string().optional(),
        address: z.string(),
      })
    )
    .optional(),
  bcc: z
    .array(
      z.object({
        name: z.string().optional(),
        address: z.string(),
      })
    )
    .optional(),
  attachments: z
    .array(
      z.object({
        id: z.string().ulid(),
        filename: z.string(),
        mimeType: z.string(),
        size: z.number(),
        storagePath: z.string().optional(),
      })
    )
    .optional(),
  headers: z.record(z.string()).optional(),
  status: MissiveStatus,
  classification: z.string().optional(),
  folder: z.string().optional(),                   // folder slug (inbox, archived, invoices, complaints, or custom)
  accountEmail: z.string().optional(),            // which account this was synced from (e.g. user@gmail.com)
  entityIds: z.array(z.string()).optional(),     // denormalized refs to Pathway entity IDs
  organizations: z.array(z.string()).optional(), // organization names this missive belongs to
  projects: z.array(z.string()).optional(), // project names this missive belongs to
  receivedAt: z.string().datetime(),
  createdAt: z.string().datetime(),
  updatedAt: z.string().datetime(),
});
export type Missive = z.infer<typeof MissiveSchema>;

// ──────────────────────────────────────────────
// Thread — A collection of related Missives
// ──────────────────────────────────────────────

export const ThreadSchema = z.object({
  id: z.string().ulid(),
  provider: ConnectorProvider,
  providerThreadId: z.string(),
  subject: z.string().optional(),
  participants: z.array(
    z.object({
      name: z.string().optional(),
      address: z.string(),
    })
  ),
  messageCount: z.number(),
  missiveIds: z.array(z.string().ulid()),
  entityIds: z.array(z.string()).optional(),     // denormalized refs to Pathway entity IDs
  summary: z.string().optional(),                // generated by Missive AI
  lastActivityAt: z.string().datetime(),
  createdAt: z.string().datetime(),
  updatedAt: z.string().datetime(),
});
export type Thread = z.infer<typeof ThreadSchema>;

